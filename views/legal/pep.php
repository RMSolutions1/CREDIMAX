  <h1>Declaración de Persona Expuesta Políticamente (PEP)</h1>
  <p>Conforme normativa de prevención de lavado de activos, al operar en Credimax debés declarar si sos Persona Expuesta Políticamente (PEP) o relacionado/a cercano/a de una PEP.</p>
  <h2>¿Quién es PEP?</h2>
  <p>Quien desempeña o desempeñó funciones públicas destacadas en el país o el exterior (poderes del Estado, organismos internacionales, etc.), y ciertos familiares o allegados.</p>
  <h2>Obligación</h2>
  <p>La declaración se realiza en el onboarding. Si tu situación cambia, actualizala desde tu perfil/soporte. La omisión o falsedad puede implicar rechazo o cierre de cuenta.</p>
