  <h2>1. Aceptación</h2>
  <p>Al crear una cuenta o usar Credimax aceptás estos Términos, la Política de Privacidad, el Manual Operativo P2P, el <a href="<?= e(url('/legales/cumplimiento')) ?>">Marco regulatorio</a> y, cuando corresponda, el Contrato de Crédito. Si no estás de acuerdo, no uses la plataforma.</p>

  <h2>2. Ámbito</h2>
  <p>Servicio exclusivo para residentes en la República Argentina, mayores de 18 años, operaciones en pesos (ARS). Queda prohibido el uso desde o hacia jurisdicciones no admitidas o por no residentes.</p>

  <h2>3. Naturaleza del servicio</h2>
  <p>Credimax provee una plataforma tecnológica de (i) acercamiento entre particulares para créditos en pesos (P2P), (ii) billetera/cuenta interna de la plataforma, y (iii) herramientas de pago internas. <strong>Credimax no es un banco</strong> bajo la Ley 21.526 ni ofrece garantía SODESA. Los saldos son registros del ledger Credimax y/o de un PSP/banco aliado cuando se integre; no constituyen depósito bancario.</p>

  <h2>4. Elegibilidad</h2>
  <p>Debés tener entre 18 y 74 años, capacidad legal, DNI argentino vigente, residencia en Argentina, email y celular propios. Una persona = una cuenta. Está prohibido operar en nombre de terceros sin mandato válido.</p>

  <h2>5. Cuenta y autenticación</h2>
  <p>Sos responsable de la confidencialidad de tu contraseña, tokens API y dispositivos. Notificá de inmediato cualquier uso no autorizado. Podemos suspender cuentas ante sospecha de fraude, lavado de activos o incumplimiento.</p>

  <h2>6. Verificación de identidad (KYC) y PLA/FT</h2>
  <p>Para operar créditos/inversiones debés completar KYC: datos filiatorios, OTP, DNI frente/dorso, selfie, declaración PEP y, si se requiere, domicilio e ingresos. Credimax puede aprobar, rechazar, limitar o pedir información adicional conforme políticas de prevención de lavado de activos y financiamiento del terrorismo (Ley 25.246 y normas UIF aplicables). El scoring interno es orientativo.</p>

  <h2>7. Créditos entre particulares</h2>
  <p>Las solicitudes son ofertas a ser fondeadas por usuarios inversores. Credimax facilita matching, documentación, cobranza operativa y distribución, pero <strong>el riesgo de crédito es exclusivamente del inversor</strong>. El inversor conserva la decisión de otorgar cada crédito. El solicitante se obliga a pagar capital, intereses, comisiones y cargos según el contrato y el cronograma.</p>

  <h2>8. Costos y transparencia</h2>
  <p>Pueden aplicarse interés (TNA), comisión de originación (financiada en cuotas), mora y otros informados antes de confirmar. Se informan TNA, TEA, CFT TNA y CFT TEA (este último con IVA estimado sobre intereses y comisión, criterio BCRA / exposición tipo BNA). El simulador muestra valores orientativos; prevalece lo aceptado contractualmente. El solicitante recibe el 100% del monto pedido; los gastos adicionales se capitalizan en el plan de pagos.</p>

  <h2>9. Billetera y pagos internos</h2>
  <p>Los movimientos dentro de Credimax son registros internos. Identificadores tipo CVU/alias/QR son de uso en la red Credimax salvo integración con PSP/banco autorizado. En producción, el ingreso/egreso de dinero de clientes se cursará por cuentas bancarias o de pago segregadas conforme normativa BCRA aplicable.</p>

  <h2>10. Conductas prohibidas</h2>
  <p>Fraude, usurpación de identidad, multipledad de cuentas, lavado de activos, financiamiento del terrorismo, abuso del marketplace u operaciones que vulneren normas argentinas.</p>

  <h2>11. Responsabilidad</h2>
  <p>Credimax no responde por mora o insolvencia de deudores ni garantiza rendimientos. No responde por interrupciones de terceros (hosting/ISP). Cuando corresponda responsabilidad contractual, se limita a comisiones cobradas en los 3 meses previos al hecho, sin perjuicio de derechos irrenunciables del consumidor.</p>

  <h2>12. Modificaciones</h2>
  <p>Podemos actualizar estos Términos publicando una nueva versión. El uso continuado implica aceptación, sin perjuicio de notificaciones cuando la ley lo exija.</p>

  <h2>13. Ley y jurisdicción</h2>
  <p>Se rigen por las leyes de la República Argentina. Tribunales ordinarios competentes según domicilio del consumidor o CABA, conforme Ley 24.240 y normas procesales aplicables.</p>

