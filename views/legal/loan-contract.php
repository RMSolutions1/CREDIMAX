  <h1>Contrato marco de crédito Credimax</h1>
  <p class="muted">Modelo aplicable a créditos P2P celebrados en la plataforma. Se completa con la solicitud, cronograma y condiciones particulares aceptadas digitalmente.</p>
  <h2>Partes</h2>
  <p><strong>Deudor/a:</strong> usuario solicitante verificado. <strong>Acreedores:</strong> uno o más usuarios inversores que fondean. <strong>Plataforma:</strong> Credimax, en carácter de administrador tecnológico y agente de cobro/pago.</p>
  <h2>Objeto</h2>
  <p>Mutuo en dinero en ARS. El Deudor recibe el 100% del monto solicitado en su billetera Credimax una vez fondeado el crédito. La comisión de originación y gastos aplicables se capitalizan (se suman al monto financiado) y se amortizan junto con intereses en el plan de cuotas.</p>
  <h2>Capital, interés y plazo</h2>
  <p>Constan en la solicitud aceptada: capital, TNA, plazo en meses, valor de cuota (sistema francés), total a pagar y fechas de vencimiento.</p>
  <h2>Pago</h2>
  <p>El Deudor autoriza el débito desde su billetera Credimax. El pago se imputa a intereses, cargos y capital. La mora genera cargos según producto y puede reportarse internamente.</p>
  <h2>Incumplimiento</h2>
  <p>Falta de pago habilita gestión de cobranza, suspensión de beneficios y, en su caso, acciones legales. Los inversores asumen el riesgo residual de incobrabilidad.</p>
  <h2>Cesión y endoso</h2>
  <p>Credimax puede ceder o endosar derechos de cobro para gestión. Los inversores mantienen su participación económica proporcional.</p>
  <h2>Firma electrónica</h2>
  <p>La aceptación en la plataforma con usuario autenticado constituye firma electrónica simple / consentimiento inequívoco del contrato y anexos.</p>
