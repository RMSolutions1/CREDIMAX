<section class="section">
  <h1>Fideicomiso y segregación de fondos</h1>
  <p class="section-lead">Estructura patrimonial alineada al modelo de créditos entre particulares (PSCPP): los fondos de inversores se administran de forma segregada respecto del patrimonio operativo de Credimax.</p>

  <div class="panel">
    <h2>Cómo opera</h2>
    <ol class="steps">
      <li>El inversor transfiere fondos a la cuenta operativa / fiduciaria indicada por Credimax.</li>
      <li>Tras la confirmación, el saldo queda disponible en su billetera para fondear créditos.</li>
      <li>Al fondear, el capital se reserva y, al completar el 100%, se desembolsa al solicitante.</li>
      <li>Las cuotas cobradas se prorratean a los inversores participantes.</li>
    </ol>
  </div>

  <div class="panel" style="margin-top:1rem">
    <h2>Lo que Credimax no es</h2>
    <ul class="muted" style="line-height:1.7">
      <li>No es entidad financiera autorizada por el BCRA.</li>
      <li>No garantiza el cobro ni el rendimiento de las inversiones.</li>
      <li>No cuenta con seguro de depósitos (Ley 24.485 / SODESA).</li>
      <li>La adhesión al esquema se formaliza en el <a href="<?= e(url('/legales/adhesion')) ?>">Contrato de adhesión</a>.</li>
    </ul>
  </div>

  <p class="muted">La instrumentación notarial/fiduciaria definitiva se completa con el estudio jurídico y el fiduciario designado en producción. Ver <a href="<?= e(url('/legales/cumplimiento')) ?>">Marco regulatorio</a>.</p>
</section>
