<section class="section">
  <h1>Contrato de adhesión</h1>
  <p class="section-lead">Al registrarte y operar en Credimax adherís a las reglas de la plataforma de créditos entre particulares y al esquema de segregación de fondos.</p>

  <div class="panel">
    <h2>Objeto</h2>
    <p>Credimax presta un servicio tecnológico para conectar solicitantes e inversores. El riesgo crediticio es de las partes. Credimax percibe comisiones de plataforma informadas en <a href="<?= e(url('/costos')) ?>">Costos</a> y en cada simulación (CFT).</p>

    <h2>Fondos</h2>
    <p>Los aportes de inversores se destinan a fondear créditos publicados. Mientras no estén fondeados, permanecen disponibles en la billetera del usuario bajo el esquema de segregación descrito en <a href="<?= e(url('/legales/fideicomiso')) ?>">Fideicomiso</a>.</p>

    <h2>Decisión de inversión</h2>
    <p>Cada fondeo requiere aprobación expresa del inversor. No hay colocación automática de capital propio de la plataforma en modalidad PSCPP.</p>

    <h2>Desistimiento</h2>
    <p>Podés ejercer el <a href="<?= e(url('/legales/arrepentimiento')) ?>">botón de arrepentimiento</a> y la <a href="<?= e(url('/legales/baja')) ?>">baja de cuenta</a> conforme Ley 24.240, sujeto a no tener operaciones activas incompatibles.</p>
  </div>

  <p class="muted">Este texto es el marco contractual de la plataforma. En producción se complementa con el instrumento firmado ante fiduciario/estudio jurídico.</p>
