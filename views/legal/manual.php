  <h1>Manual operativo P2P</h1>
  <p class="muted">Alineado al marco BCRA de créditos entre particulares (PSCPP) · Argentina · ARS</p>

  <h2>1. Roles</h2>
  <p>Solicitante (tomador), Inversor (oferente) y Credimax (plataforma tecnológica). Credimax y personas vinculadas <strong>no</strong> actúan como oferentes ni demandantes de crédito en la modalidad PSCPP.</p>

  <h2>2. Alta y admisión</h2>
  <p>Registro (residencia Argentina) → onboarding → OTP → KYC/PEP → scoring → aprobación. Sin KYC aprobado no se publica ni se fondea.</p>

  <h2>3. Publicación de solicitudes</h2>
  <p>El solicitante elige producto, monto, plazo y motivo. Se informa TNA/TEA/CFT estimados. Cronograma y código LN-…. Estado: open/funding. El monto pedido se desembolsa íntegro; gastos se financian en cuotas.</p>

  <h2>4. Fondeo</h2>
  <p>El inversor revisa la solicitud y <strong>aprueba manualmente</strong> el monto a fondear. Se reserva saldo. Al completar el 100% se desembolsa. No hay fondeo automático ni garantía de colocación.</p>

  <h2>5. Identificación y documentación</h2>
  <p>Antes de fondear, el inversor accede a información de riesgo/crédito necesaria para decidir. Tras la operación, las partes disponen de la documentación para ejercer derechos.</p>

  <h2>6. Cobranza y distribución</h2>
  <p>Cada cuota pagada se prorratea entre fondeos activos. La mora se marca overdue. Credimax puede gestionar cobranza operativa; el inversor puede retirar/gestionar el crédito conforme reglas de la plataforma y la norma aplicable.</p>

  <h2>7. Riesgos</h2>
  <p>No hay garantía de capital ni de rendimiento. El inversor asume el riesgo de crédito. Diversificación recomendada.</p>

  <h2>8. Fondos</h2>
  <p>En producción, ingresos y egresos de clientes se cursan por cuentas bancarias o de pago segregadas (entidad financiera / PSP), distintas de la cuenta operativa de Credimax.</p>

  <h2>9. Conflictos</h2>
  <p>Reclamos vía Centro de ayuda / Contacto. Disputas de fondo pueden judicializarse bajo ley argentina.</p>
