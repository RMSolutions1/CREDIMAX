  <h1>Política de Privacidad</h1>
  <p class="muted">Versión 1.0 · Credimax</p>
  <h2>1. Responsable</h2>
  <p>Credimax trata datos personales para operar la plataforma de créditos P2P, billetera y cumplimiento KYC/AML.</p>
  <h2>2. Datos que reunimos</h2>
  <ul>
    <li>Identificación: nombre, DNI/CUIT, fecha de nacimiento, domicilio, selfie y documentos.</li>
    <li>Contacto: email, teléfono y verificaciones OTP.</li>
    <li>Laborales/financieros: empleo, ingresos, score interno, operaciones.</li>
    <li>Técnicos: IP, dispositivo, logs de seguridad y cookies necesarias.</li>
  </ul>
  <h2>3. Finalidades</h2>
  <p>Crear y administrar cuentas; verificar identidad; evaluar riesgo; ejecutar créditos/pagos; prevenir fraude; soporte; obligaciones legales.</p>
  <h2>4. Base</h2>
  <p>Ejecución contractual, consentimiento (cuando corresponde) e interés legítimo de seguridad/prevención de fraude, conforme Ley 25.326.</p>
  <h2>5. Cesiones</h2>
  <p>No vendemos datos. Podemos compartir con proveedores de infraestructura bajo confidencialidad, autoridades competentes y, en forma anonimizada, estadísticas. En el marketplace P2P los inversores ven información de riesgo/crédito <strong>sin datos personales identificatorios innecesarios</strong>.</p>
  <h2>6. Conservación</h2>
  <p>Mientras la cuenta esté activa y los plazos legales de conservación (operaciones financieras / prevención de lavado) lo requieran.</p>
  <h2>7. Derechos</h2>
  <p>Acceso, rectificación y actualización ante Credimax vía <a href="<?= e(url('/contacto')) ?>">Contacto</a>. También podés ejercer derechos ante la AAIP.</p>
  <h2>8. Seguridad</h2>
  <p>Cifrado en tránsito (HTTPS en producción), hashing de contraseñas, control de acceso, auditoría y almacenamiento restringido de documentos KYC.</p>
