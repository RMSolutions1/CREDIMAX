  <h1>Información al consumidor financiero</h1>
  <p class="muted">Ley 24.240 · Transparencia de costos · Argentina</p>
  <p>Antes de contratar un crédito en Credimax tenés derecho a conocer:</p>
  <ul>
    <li>Monto a recibir (100% del solicitado) y total a pagar (incluye gastos financiados)</li>
    <li>Cantidad y valor de cuotas</li>
    <li>TNA, TEA, CFT TNA y CFT TEA (con IVA estimado sobre intereses y comisión)</li>
    <li>Comisiones y cargos por mora</li>
    <li>Cronograma de vencimientos</li>
    <li>Medios de pago y consecuencias del incumplimiento</li>
  </ul>
  <p>Credimax no es entidad financiera del BCRA. Si participás como inversor, asumís el riesgo de crédito y no hay garantía de cobro.</p>
  <p>Podés desistir según normativa aplicable de defensa del consumidor cuando corresponda, contactando soporte antes del desembolso o conforme plazos legales.</p>
