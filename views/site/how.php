  <h1>Cómo funciona Credimax</h1>
  <p class="section-lead">Modelo de créditos e inversiones entre personas: la plataforma conecta solicitantes e inversores. Credimax no es entidad financiera ni garantiza el cobro.</p>

  <ol class="steps steps-4">
    <li>
      <strong>Paso 1 — Registro</strong>
      <p>Inversores y solicitantes se registran 24/7, aceptan términos, adhesión y completan KYC.</p>
    </li>
    <li>
      <strong>Paso 2 — Publicación y fondeo</strong>
      <p>Las solicitudes admitidas se publican en el mercado. Cada inversor decide cuánto fondear.</p>
    </li>
    <li>
      <strong>Paso 3 — Desembolso</strong>
      <p>Cuando se financia el 100%, el solicitante recibe el dinero en su billetera Credimax.</p>
    </li>
    <li>
      <strong>Paso 4 — Cobro y retorno</strong>
      <p>Las cuotas pagadas se prorratean automáticamente entre los inversores que fondearon.</p>
    </li>
  </ol>

