<section class="section">
  <h1>Requisitos</h1>
  <div class="grid-2">
    <article class="panel">
      <h2>Para solicitar crédito</h2>
      <ul>
        <li>Edad entre 18 y 74 años</li>
        <li>DNI argentino vigente</li>
        <li>Email y celular propios</li>
        <li>Domicilio en Argentina</li>
        <li>Ingresos demostrables (relación de dependencia, monotributo u otros)</li>
        <li>Antigüedad laboral recomendada ≥ 6 meses</li>
        <li>KYC aprobado (DNI + selfie)</li>
        <li>Aceptación de Términos, Privacidad y Contrato</li>
        <li>No estar suspendido en Credimax</li>
      </ul>
    </article>
    <article class="panel">
      <h2>Para invertir / prestar</h2>
      <ul>
        <li>Mismos requisitos de identidad</li>
        <li>KYC aprobado</li>
        <li>Saldo disponible en billetera Credimax</li>
        <li>Declaración PEP completada</li>
        <li>Comprensión del Manual operativo P2P y riesgos de mora</li>
      </ul>
    </article>
  </div>
  <h2>Métodos de verificación de identidad</h2>
  <ol class="steps">
    <li><strong>Datos filiatorios</strong> — nombre, DNI/CUIT, fecha de nacimiento, domicilio.</li>
    <li><strong>OTP</strong> — código a email y/o celular.</li>
    <li><strong>Documento</strong> — foto nítida de DNI frente y dorso.</li>
    <li><strong>Biometría liviana</strong> — selfie (y opcionalmente selfie con DNI).</li>
    <li><strong>Domicilio / ingresos</strong> — servicio o constancia (refuerza scoring).</li>
    <li><strong>Revisión humana</strong> — el equipo admin aprueba o rechaza KYC.</li>
    <li><strong>Scoring interno</strong> — banda A–E sin depender de Veraz/Nosis externos.</li>
  </ol>
